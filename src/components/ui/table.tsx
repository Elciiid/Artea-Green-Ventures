"use client"

import * as React from "react"

import { cn } from "@/lib/utils"

// Padding-override trap, hit once already (see git history for
// ApplicationRegister.tsx): tailwind-merge does not treat a shorthand `p-*`
// class as conflicting with `py-*`/`pr-*`/`pl-*`/`pt-*`/`pb-*`, so a base
// className's `p-*` (TableCell/TableFooter below) or `px-*`/`py-*`
// (TableHead) survives untouched in the merged string. Standard Tailwind
// cascade order then lets a longhand override win ONLY for the sides it
// explicitly sets — any side your override doesn't touch keeps the
// surviving base value. Concretely: overriding TableCell's `p-2` with just
// `py-3.5 pr-4` silently leaves an 8px padding-left from the base; the fix
// is either an equally-shaped shorthand (`p-0`) to force tailwind-merge to
// drop the base entirely, or longhand overrides that explicitly cover every
// side the base shorthand touches. This isn't specific to `p-2` — the same
// applies to any shorthand base (including `px-*`/`py-*`) paired with a
// partial longhand override.

function Table({ className, ...props }: React.ComponentProps<"table">) {
  return (
    <div
      data-slot="table-container"
      className="relative w-full overflow-x-auto"
    >
      <table
        data-slot="table"
        className={cn("w-full caption-bottom text-sm", className)}
        {...props}
      />
    </div>
  )
}

function TableHeader({ className, ...props }: React.ComponentProps<"thead">) {
  return (
    <thead
      data-slot="table-header"
      className={cn("[&_tr]:border-b", className)}
      {...props}
    />
  )
}

function TableBody({ className, ...props }: React.ComponentProps<"tbody">) {
  return (
    <tbody
      data-slot="table-body"
      className={cn("[&_tr:last-child]:border-0", className)}
      {...props}
    />
  )
}

function TableFooter({ className, ...props }: React.ComponentProps<"tfoot">) {
  return (
    <tfoot
      data-slot="table-footer"
      className={cn(
        "border-t bg-muted/50 font-medium [&>tr]:last:border-b-0",
        className
      )}
      {...props}
    />
  )
}

function TableRow({ className, ...props }: React.ComponentProps<"tr">) {
  return (
    <tr
      data-slot="table-row"
      className={cn(
        "border-b transition-colors hover:bg-muted/50 has-aria-expanded:bg-muted/50 data-[state=selected]:bg-muted",
        className
      )}
      {...props}
    />
  )
}

function TableHead({ className, ...props }: React.ComponentProps<"th">) {
  return (
    <th
      data-slot="table-head"
      className={cn(
        "h-10 px-2 text-left align-middle font-medium whitespace-nowrap text-foreground [&:has([role=checkbox])]:pr-0",
        className
      )}
      {...props}
    />
  )
}

function TableCell({ className, ...props }: React.ComponentProps<"td">) {
  return (
    <td
      data-slot="table-cell"
      className={cn(
        "p-2 align-middle whitespace-nowrap [&:has([role=checkbox])]:pr-0",
        className
      )}
      {...props}
    />
  )
}

function TableCaption({
  className,
  ...props
}: React.ComponentProps<"caption">) {
  return (
    <caption
      data-slot="table-caption"
      className={cn("mt-4 text-sm text-muted-foreground", className)}
      {...props}
    />
  )
}

export {
  Table,
  TableHeader,
  TableBody,
  TableFooter,
  TableHead,
  TableRow,
  TableCell,
  TableCaption,
}
